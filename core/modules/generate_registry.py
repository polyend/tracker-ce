#!/usr/bin/env python3
"""Generate registerFeatureModules() from external feature-module directories.

Each module directory must contain module.mk defining:
  MODULE_NAME, MODULE_INSTANCE, MODULE_HEADER
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


def parse_module_mk(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    pattern = re.compile(r"^\s*([A-Z_][A-Z0-9_]*)\s*:?=\s*(.*?)\s*$")
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.split("#", 1)[0].strip()
        if not stripped:
            continue
        match = pattern.match(stripped)
        if match:
            values[match.group(1)] = match.group(2).strip()
    return values


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("-o", "--output", required=True)
    parser.add_argument("module_dirs", nargs="*")
    args = parser.parse_args()

    modules: list[dict[str, str]] = []
    for raw_dir in args.module_dirs:
        module_dir = Path(raw_dir).resolve()
        module_mk = module_dir / "module.mk"
        if not module_mk.is_file():
            print(f"error: missing module.mk in {module_dir}", file=sys.stderr)
            return 1
        values = parse_module_mk(module_mk)
        for key in ("MODULE_NAME", "MODULE_INSTANCE", "MODULE_HEADER"):
            if key not in values or not values[key]:
                print(f"error: {module_mk} missing {key}", file=sys.stderr)
                return 1
        values["MODULE_DIR"] = str(module_dir)
        try:
            values["_ORDER"] = int(values.get("MODULE_ORDER", "100"))
        except ValueError:
            values["_ORDER"] = 100
        modules.append(values)

    # Registration order = Performance page cycle order (MODULE_ORDER, then name).
    modules.sort(key=lambda m: (m["_ORDER"], m["MODULE_NAME"]))

    lines = [
        "// Auto-generated by core/modules/generate_registry.py — do not edit.",
        '#include "FeatureModuleRegistry.h"',
        "",
    ]

    for module in modules:
        header = module["MODULE_HEADER"]
        lines.append(f'#include "{header}"')

    lines.extend(
        [
            "",
            "void registerFeatureModules(FeatureModuleRegistry& registry)",
            "{",
            "    registry.clear();",
        ]
    )

    for module in modules:
        instance = module["MODULE_INSTANCE"]
        lines.append(f"    registry.add(&{instance});")

    lines.extend(["}", ""])

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines)
    if output.exists() and output.read_text(encoding="utf-8") == text:
        return 0
    output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
